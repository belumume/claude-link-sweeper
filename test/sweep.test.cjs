// Runs the sweeper against a fake GitHub API and checks every write it makes.
const assert = require('assert');
process.env.SWEEP_TOKEN = 'test';
process.env.REPORT_REPO = 'me/private-report';
const sweep = require('../scripts/sweep.cjs');

const L = 'https://' + 'claude' + '.ai/code';
const FOOTER = `Done.\n\n---\n_Generated by [Claude Code](${L})_`;
const ID = 'session' + '_01' + 'X'.repeat(24);
const R = '/repos/me/site';
const writes = [];
const data = {
  '/user': { login: 'me' },
  // me/quiet has no recent activity, so any request for it fails the test
  '/user/repos': [
    { full_name: 'me/site', pushed_at: '2999-01-01T00:00:00Z' },
    { full_name: 'me/old', archived: true },
    { full_name: 'me/quiet', pushed_at: '2000-01-01T00:00:00Z' },
  ],
  '/search/issues': { incomplete_results: false, items: [{ repository_url: 'https://api.github.com/repos/me/site' }] },
  [`${R}/issues`]: [
    { number: 2, title: 'Add page', body: `Body\n\n${L}/session_x`, pull_request: {} },
    { number: 5, title: 'Clean issue', body: 'nothing here' },
  ],
  [`${R}/pulls/2/reviews`]: [{ id: 7, body: `See ${ID}` }, { id: 8, body: '' }],
  [`${R}/issues/comments`]: [
    { id: 11, body: FOOTER, user: { login: 'me' }, issue_url: 'https://api.github.com/repos/me/site/issues/2' },
    { id: 12, body: `[Fix this →](${L}?q=x)`, user: { login: 'claude[bot]' }, issue_url: 'x/2' },
    { id: 13, body: 'clean', user: { login: 'me' }, issue_url: 'x/2' },
  ],
  [`${R}/pulls/comments`]: [
    { id: 21, body: FOOTER, user: { login: 'me' }, in_reply_to_id: 20, pull_request_url: 'x/pulls/2' },
    { id: 22, body: FOOTER, user: { login: 'me' }, pull_request_url: 'x/pulls/2' },
  ],
  [`${R}/branches`]: [{ name: 'main' }, { name: 'feature' }],
  [`${R}/commits`]: [
    { sha: 'a'.repeat(40), commit: { message: `Fix\n\nSee ${L}/x` } },
    { sha: 'b'.repeat(40), commit: { message: 'Clean' } },
  ],
  '/repos/me/private-report/issues': [],
};
sweep.setFetch(async (url, opts) => {
  const path = url.replace('https://api.github.com', '').split('?')[0];
  if (opts.method !== 'GET') {
    writes.push([opts.method, path, opts.body ? JSON.parse(opts.body) : null]);
    return { ok: true, status: opts.method === 'DELETE' ? 204 : 200, json: async () => ({}) };
  }
  const page = Number((url.match(/[?&]page=(\d+)/) || [0, 1])[1]);
  const value = data[path];
  if (value === undefined) throw new Error('unexpected GET ' + path);
  return { ok: true, status: 200, json: async () => (Array.isArray(value) && page > 1 ? [] : value) };
});

(async () => {
  const ok = await sweep.main();
  assert.strictEqual(ok, true);
  const find = (m, p) => writes.filter((w) => w[0] === m && w[1] === p);
  // PR body edited, title untouched, clean issue untouched
  assert.deepStrictEqual(find('PATCH', `${R}/pulls/2`).map((w) => Object.keys(w[2])), [['body']]);
  assert.strictEqual(find('PATCH', `${R}/issues/5`).length, 0);
  // Review with a bare ID edited, empty one untouched
  assert.strictEqual(find('PUT', `${R}/pulls/2/reviews/7`)[0][2].body, 'See');
  assert.strictEqual(find('PUT', `${R}/pulls/2/reviews/8`).length, 0);
  // Own comment reposted then deleted, keeping the plain credit
  assert.strictEqual(find('POST', `${R}/issues/2/comments`)[0][2].body, 'Done.\n\n---\n_Generated by Claude Code_');
  assert.strictEqual(find('DELETE', `${R}/issues/comments/11`).length, 1);
  // Bot comment edited, not reposted
  assert.strictEqual(find('PATCH', `${R}/issues/comments/12`).length, 1);
  assert.strictEqual(find('DELETE', `${R}/issues/comments/12`).length, 0);
  assert.strictEqual(find('PATCH', `${R}/issues/comments/13`).length, 0);
  // Own thread reply reposted into its thread; thread opener edited in place
  assert.strictEqual(find('POST', `${R}/pulls/2/comments/20/replies`).length, 1);
  assert.strictEqual(find('DELETE', `${R}/pulls/comments/21`).length, 1);
  assert.strictEqual(find('PATCH', `${R}/pulls/comments/22`).length, 1);
  assert.strictEqual(find('DELETE', `${R}/pulls/comments/22`).length, 0);
  // Linked commit listed once (two branches) in a new report issue; nothing else written
  const report = find('POST', '/repos/me/private-report/issues');
  assert.strictEqual(report.length, 1);
  assert.strictEqual(report[0][2].body.split('\n').filter((l) => l.startsWith('- ')).length, 1);
  assert.ok(report[0][2].body.includes('me/site@aaaaaaaaaaaa'));
  for (const w of writes) assert.ok(!JSON.stringify(w[2] || {}).includes('claude' + '.ai'), 'link left in ' + w[1]);
  assert.strictEqual(writes.length, 9);
  console.log('sweep tests passed (' + writes.length + ' writes checked)');
})().catch((e) => { console.error(e); process.exit(1); });
